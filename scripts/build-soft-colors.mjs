// Builds the curated colorways the Soft, Med and Hard buttons deal from:
//   src/data/colorways.json                -> src/data/soft-colors.ts (type specimens)
//   src/data/alex-cristache-colorways.json -> src/data/alex-cristache-colors.ts (Alex Cristache)
// Keeps a colorway only if some ink on it reaches 3:1 against its background
// (WCAG AA for large text), so it stays readable without losing the softer,
// lower-contrast combinations.
//
// Each colorway records its source, and a bucket set by how hard it hits, not
// by where it came from: both sources run from gentle to loud.
//
//   node scripts/build-soft-colors.mjs

import { readFileSync, writeFileSync } from 'node:fs'

const MIN_CONTRAST = 3

function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

function contrast(a, b) {
  const [lo, hi] = [luminance(a), luminance(b)].sort((x, y) => x - y)
  return (hi + 0.05) / (lo + 0.05)
}

const srgbToLinear = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)

/** OKLCH chroma of a hex color. */
function chroma(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => srgbToLinear(parseInt(hex.slice(i, i + 2), 16) / 255))
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
  const a = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s
  const bb = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s
  return Math.hypot(a, bb)
}

/**
 * How hard a colorway hits, in contrast-ratio units. Ink contrast leads, body
 * weighted over heading since it covers more of the page (a geometric mean).
 * Saturation adds weight past a chroma of 0.1, up to double by 0.22, so a
 * cream-on-poppy page at 4.5:1 doesn't pass for soft.
 */
function hardness({ bg, heading, body }) {
  const ink = contrast(body, bg) ** 0.7 * contrast(heading, bg) ** 0.3
  const vivid = Math.min(1, Math.max(0, (Math.max(...[bg, heading, body].map(chroma)) - 0.1) / 0.12))
  return ink * (1 + vivid)
}

// Fixed cut lines, so a colorway's bucket doesn't move when others are added
const SOFT_BELOW = 6
const HARD_FROM = 11

function bucket(colorway) {
  const h = hardness(colorway)
  return h < SOFT_BELOW ? 'soft' : h < HARD_FROM ? 'med' : 'hard'
}

function readable(colorways) {
  const out = []
  const seen = new Set()

  for (const cw of colorways) {
    const bg = cw.background.toLowerCase()
    const inks = [...cw.foreground, ...cw.accents]
      .map((c) => c.toLowerCase())
      .filter((c, i, all) => c !== bg && all.indexOf(c) === i && contrast(c, bg) >= MIN_CONTRAST)
    if (inks.length === 0) continue

    // Body: the designer's main foreground if it reads, else the strongest ink.
    // Heading: the first other ink that reads, so the accent gets a showing.
    const fg = cw.foreground.map((c) => c.toLowerCase())
    const body = inks.includes(fg[0])
      ? fg[0]
      : inks.reduce((a, b) => (contrast(b, bg) > contrast(a, bg) ? b : a))
    const heading = inks.find((c) => c !== body) ?? body

    const key = `${bg}|${heading}|${body}`
    if (seen.has(key)) continue
    seen.add(key)
    out.push({ name: cw.name, bg, heading, body })
  }
  return out
}

function rows(list, source) {
  return list
    .map(
      (c) =>
        `  { name: ${JSON.stringify(c.name)}, bg: "${c.bg}", heading: "${c.heading}", body: "${c.body}", source: "${source}", bucket: "${bucket(c)}" },`
    )
    .join('\n')
}

function build({ src, out, header, constName, source }) {
  const { colorways } = JSON.parse(readFileSync(src, 'utf8'))
  const list = readable(colorways)
  writeFileSync(
    out,
    `// Generated by scripts/build-soft-colors.mjs from ${src}. Do not edit.
${header}
export const ${constName}: Colorway[] = [
${rows(list, source)}
]
`
  )
  const count = (b) => list.filter((c) => bucket(c) === b).length
  console.log(
    `${out}: ${list.length} of ${colorways.length} colorways kept (>= ${MIN_CONTRAST}:1); soft ${count('soft')}, med ${count('med')}, hard ${count('hard')}`
  )
}

build({
  src: 'src/data/colorways.json',
  out: 'src/data/soft-colors.ts',
  constName: 'SPECIMEN_COLORWAYS',
  source: 'specimen',
  header: `
/** Where a colorway was collected: type specimen images, or Alex Cristache's palette graphics. */
export type ColorwaySource = "specimen" | "alex-cristache"

/** How hard a colorway hits, from scripts/build-soft-colors.mjs. The Soft, Med and Hard buttons deal by this. */
export type ColorwayBucket = "soft" | "med" | "hard"

export interface Colorway {
  name: string
  bg: string
  heading: string
  body: string
  source: ColorwaySource
  bucket: ColorwayBucket
}
`,
})

build({
  src: 'src/data/alex-cristache-colorways.json',
  out: 'src/data/alex-cristache-colors.ts',
  constName: 'ALEX_CRISTACHE_COLORWAYS',
  source: 'alex-cristache',
  header: `
import type { Colorway } from "./soft-colors"
`,
})
