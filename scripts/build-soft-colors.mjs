// Builds the colorway decks the color buttons deal from:
//   src/data/colorways.json               -> src/data/soft-colors.ts (Soft)
//   src/data/alex-cristache-colorways.json -> src/data/alex-cristache-colors.ts (Alex)
// Keeps a colorway only if some ink on it reaches 3:1 against its background
// (WCAG AA for large text), so it stays readable without losing the softer,
// lower-contrast combinations.
//
//   node scripts/build-soft-colors.mjs

import { readFileSync, writeFileSync } from 'node:fs'

const MIN_CONTRAST = 3

function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

function contrast(a, b) {
  const [lo, hi] = [luminance(a), luminance(b)].sort((x, y) => x - y)
  return (hi + 0.05) / (lo + 0.05)
}

function readable(colorways) {
  const out = []
  const seen = new Set()

  for (const cw of colorways) {
    const bg = cw.background.toLowerCase()
    const inks = [...cw.foreground, ...cw.accents]
      .map((c) => c.toLowerCase())
      .filter((c, i, all) => c !== bg && all.indexOf(c) === i && contrast(c, bg) >= MIN_CONTRAST)
    if (inks.length === 0) continue

    // Body: the designer's main foreground if it reads, else the strongest ink.
    // Heading: the first other ink that reads, so the accent gets a showing.
    const fg = cw.foreground.map((c) => c.toLowerCase())
    const body = inks.includes(fg[0])
      ? fg[0]
      : inks.reduce((a, b) => (contrast(b, bg) > contrast(a, bg) ? b : a))
    const heading = inks.find((c) => c !== body) ?? body

    const key = `${bg}|${heading}|${body}`
    if (seen.has(key)) continue
    seen.add(key)
    out.push({ name: cw.name, bg, heading, body })
  }
  return out
}

function rows(list) {
  return list
    .map((c) => `  { name: ${JSON.stringify(c.name)}, bg: "${c.bg}", heading: "${c.heading}", body: "${c.body}" },`)
    .join('\n')
}

function build({ src, out, header, constName }) {
  const { colorways } = JSON.parse(readFileSync(src, 'utf8'))
  const list = readable(colorways)
  writeFileSync(
    out,
    `// Generated by scripts/build-soft-colors.mjs from ${src}. Do not edit.
${header}
export const ${constName}: SoftColorway[] = [
${rows(list)}
]
`
  )
  console.log(`${out}: ${list.length} of ${colorways.length} colorways kept (>= ${MIN_CONTRAST}:1)`)
}

build({
  src: 'src/data/colorways.json',
  out: 'src/data/soft-colors.ts',
  constName: 'SOFT_COLORWAYS',
  header: `
export interface SoftColorway {
  name: string
  bg: string
  heading: string
  body: string
}
`,
})

build({
  src: 'src/data/alex-cristache-colorways.json',
  out: 'src/data/alex-cristache-colors.ts',
  constName: 'ALEX_CRISTACHE_COLORWAYS',
  header: `
import type { SoftColorway } from "./soft-colors"
`,
})
